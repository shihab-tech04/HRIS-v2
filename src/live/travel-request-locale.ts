export function travelRequestText(
  locale: Locale,
  english: string,
  values: Record<string, string | number> = {},
): string {
  const template = locale === 'bn' ? (bengali[english] || english) : english;
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => String(values[key] ?? `{${key}}`));
}

export function travelRequestError(locale: Locale, message: string, fallback: string): string {
  if (locale === 'en') return message || fallback;
  return bengali[message] || bengali[fallback] || fallback;
}
